def utc_now_iso() -> str:
    return (
        datetime.now(timezone.utc)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z")
    )


def normalize_host(url: str) -> str:
    """Return the www-stripped lowercase hostname of an https URL."""
    raw = str(url or "").strip()
    if not raw:
        raise ValueError("empty url")
    if not raw.lower().startswith("https://"):
        raise ValueError(f"non-https url: {raw}")
    host = raw[len("https://"):].split("/", 1)[0].split("?", 1)[0].lower()
    if not host or " " in host or ":" in host or "@" in host:
        raise ValueError(f"invalid host in url: {raw}")
    if host.startswith("www."):
        host = host[4:]
    if "." not in host:
        raise ValueError(f"host without a dot: {raw}")
    return host


def site_key_for_host(host: str) -> str:
    key = re.sub(r"[^a-z0-9]+", "-", host.lower()).strip("-")
    return key or "site"


def clean_title(raw: str) -> str:
    text = re.sub(r"<[^>]+>", " ", raw or "")
    text = html_module.unescape(text)
    return re.sub(r"\s+", " ", text).strip()[:MAX_TITLE_CHARS]


def _is_dns_failure(reason: Any, detail: str) -> bool:
    if isinstance(reason, socket.gaierror):
        return True
    lowered = detail.lower()
    return any(
        marker in lowered
        for marker in (
            "name or service not known",
            "nodename nor servname",
            "getaddrinfo failed",
            "no address associated",
            "name resolution",
        )
    )


def _decode_body(body: bytes, encoding: str) -> bytes:
    """Best-effort transparent decompression of a possibly truncated read."""
    lowered = encoding.lower()
    if body[:2] == b"\x1f\x8b" or "gzip" in lowered:
        try:
            return zlib.decompressobj(16 + zlib.MAX_WBITS).decompress(body)
        except zlib.error:
            return body
    if "deflate" in lowered:
        try:
            return zlib.decompressobj().decompress(body)
        except zlib.error:
            return body
    return body


def _title_of(text: str) -> str:
    match = re.search(r"<title[^>]*>(.*?)</title>", text, re.I | re.S)
    return clean_title(match.group(1)) if match else ""


def evaluate_document(text: str) -> Tuple[str, bool]:
    """Return (title, challenge) for one decoded document.

    A challenge flag is fail-closed evidence: strong markers always fire,
    weak Akamai markers only fire on a short stub so a real page mentioning
    an Akamai reference number is not misread as a wall.
    """
    title = _title_of(text)
    lowered = text[:200000].lower()
    challenge = (
        any(marker in title.lower() for marker in TITLE_CHALLENGE_MARKERS)
        or any(marker in lowered for marker in BODY_CHALLENGE_MARKERS)
        or (
            len(text) <= WEAK_CHALLENGE_MAX_CHARS
            and any(marker in lowered for marker in WEAK_BODY_CHALLENGE_MARKERS)
        )
    )
    return title, challenge


def _probe_once(url: str, timeout: int = PROBE_TIMEOUT_SECONDS) -> Dict[str, Any]:
    """Fetch one URL and return a flat evidence record.  Never raises."""
    record: Dict[str, Any] = {
        "url": url,
        "http_status": 0,
        "final_url": "",
        "title": "",
        "body_bytes": 0,
        "challenge": False,
        "error": "",
        "checked_at_utc": utc_now_iso(),
    }
    request = Request(
        url,
        headers={
            "User-Agent": USER_AGENT,
            "Accept": "text/html,application/xhtml+xml,application/json;q=0.9,*/*;q=0.8",
            "Accept-Language": "en-US,en;q=0.8",
        },
        method="GET",
    )
    context = ssl.create_default_context()

    def observe(body: bytes, content_encoding: str, charset: str) -> None:
        raw = _decode_body(body, content_encoding)
        try:
            text = raw.decode(charset or "utf-8", errors="replace")
        except LookupError:
            text = raw.decode("utf-8", errors="replace")
        title, challenge = evaluate_document(text)
        record["title"] = title
        record["body_bytes"] = len(raw)
        record["challenge"] = challenge

    try:
        with urlopen(request, timeout=timeout, context=context) as response:
            body = response.read(1048576)
            record["http_status"] = int(response.status)
            record["final_url"] = response.geturl() or url
            observe(
                body,
                response.headers.get("Content-Encoding") or "",
                response.headers.get_content_charset() or "",
            )
    except HTTPError as error:
        record["http_status"] = int(error.code)
        record["final_url"] = error.geturl() or url
        record["error"] = f"http_{error.code}"
        try:
            headers = error.headers
            observe(
                error.read(131072) or b"",
                (headers.get("Content-Encoding") or "") if headers else "",
                (headers.get_content_charset() or "") if headers else "",
            )
        except Exception:
            pass
    except (URLError, ssl.SSLError, TimeoutError, OSError) as error:
        reason = getattr(error, "reason", None)
        detail = str(reason if reason is not None else error)
        if _is_dns_failure(reason, detail):
            record["error"] = "dns_failure"
        elif "timed out" in detail.lower() or "timeout" in detail.lower():
            record["error"] = "timeout"
        else:
            record["error"] = "connection_failure"
    return record


def probe_url(url: str, timeout: int = PROBE_TIMEOUT_SECONDS) -> Dict[str, Any]:
    """Probe one URL, retrying one transient failure once.

    Transport failures and a first 404/410 are retried: parallel probes have
    drawn a rate-limit 404 from hosts that answer a single follow-up request
    with their real homepage.  A retry only replaces the record when it
    produces a solid answer, so repeated failures stay honest.
    """
    record = _probe_once(url, timeout)
    transient = (
        record.get("error") in ("timeout", "connection_failure")
        or int(record.get("http_status") or 0) in (404, 410)
    )
    if transient:
        time.sleep(2)
        retry = _probe_once(url, timeout)
        retry_transient = (
            retry.get("error") in ("timeout", "connection_failure")
            or int(retry.get("http_status") or 0) in (0, 404, 410)
        )
        if not retry_transient:
            record = retry
    return record


def registry_sources(
    manifest: Dict[str, Any],
) -> Tuple[Dict[str, Dict[str, str]], List[str]]:
    """Registry sources plus keys the market mapping does not cover yet."""
    digest = manifest.get("registry_digest")
    if isinstance(digest, str):
        parsed = json.loads(digest)
    elif isinstance(digest, dict):
        parsed = digest
    else:
        raise ValueError("manifest carries no registry digest")
    sources: Dict[str, Dict[str, str]] = {}
    unmapped: List[str] = []
    for item in parsed.get("sources", []):
        key = str(item.get("key") or "").strip()
        domains = item.get("domains") or []
        if not key:
            continue
        if key not in AUCTION_REGISTRY_COUNTRIES or not domains:
            unmapped.append(key)
            continue
        host = str(domains[0]).strip().lower()
        sources[key] = {
            "url": f"https://{host}/",
            "name": str(item.get("name") or key).strip() or key,
        }
    return sources, sorted(set(unmapped))


def collect_probe_targets(registry: Dict[str, Dict[str, str]]) -> List[Tuple[str, str, str]]:
    """Unique (site_key, host, url) targets from both tables."""
    seen_hosts = set()
    targets: List[Tuple[str, str, str]] = []

    def add(url: str) -> None:
        try:
            host = normalize_host(url)
        except ValueError:
            return
        if host in seen_hosts:
            return
        seen_hosts.add(host)
        targets.append((site_key_for_host(host), host, f"https://{host}/"))

    for entries in CANDIDATES.values():
        for _key, _name, url, _kind in entries:
            add(url)
    for entry in registry.values():
        add(entry["url"])
    return sorted(targets, key=lambda item: item[1])


def run_probe(
    targets: Sequence[Tuple[str, str, str]], workers: int = PROBE_WORKERS
) -> Dict[str, Any]:
    results: List[Dict[str, Any]] = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        futures = {
            pool.submit(probe_url, url): (key, host, url) for key, host, url in targets
        }
        for future in concurrent.futures.as_completed(futures):
            key, host, _url = futures[future]
            record = future.result()
            record["site_key"] = key
            record["host"] = host
            results.append(record)
    results.sort(key=lambda record: record["host"])
    return {
        "schema_version": 1,
        "lane": f"{LANE}_probe",
        "checked_at_utc": utc_now_iso(),
        "targets": len(targets),
        "results": results,
    }


def classify_probe(record: Dict[str, Any]) -> Tuple[Optional[str], str]:
    """Map one probe record to (status, reason).  status=None means excluded.

    `unreachable` means the host resolved but the probe network could not
    complete a fetch — the domain exists, the fetch is the fact that is
    missing.  Everything excluded failed on evidence about the host itself.
    """
    status = int(record.get("http_status") or 0)
    host = str(record.get("host") or "")
    if host in DISQUALIFIED_HOSTS:
        return None, "disqualified"
    if record.get("challenge") or status in GATED_STATUSES:
        return "walled", "gated"
    if status in REACHABLE_STATUSES:
        if not str(record.get("final_url") or "").lower().startswith("https://"):
            return None, "connection_failure"
        if not record.get("title") and status in (200, 204) and \
                int(record.get("body_bytes") or 0) < MIN_DOCUMENT_BYTES:
            return None, "empty_response"
        return "verified", "reachable"
    error = str(record.get("error") or "")
    if error == "dns_failure":
        return None, "dns_failure"
    if error in ("timeout", "connection_failure"):
        return "unreachable", error
    if status in (404, 410):
        return None, "http_error"
    return None, "http_error"


def build_artifact(
    probe: Dict[str, Any],
    manifest: Dict[str, Any],
    generated_at: Optional[str] = None,
) -> Dict[str, Any]:
    """Join probe evidence, the candidate table and the auction registry."""
    evidence: Dict[str, Dict[str, Any]] = {
        record["host"]: record for record in probe.get("results", [])
    }
    sites: Dict[str, Dict[str, Any]] = {}
    excluded: List[Dict[str, Any]] = []

    def add_site(
        host: str,
        name: str,
        url: str,
        kind: str,
        countries: List[str],
        source_keys: List[str],
        wired: bool,
        registry_urls: Optional[List[str]] = None,
    ) -> None:
        record = evidence.get(host)
        if record is None:
            excluded.append({
                "host": host,
                "url": url,
                "countries": sorted(set(countries)),
                "reason": "not_probed",
            })
            return
        status, reason = classify_probe(record)
        if status is None:
            if not source_keys:
                excluded.append({
                    "host": host,
                    "url": url,
                    "countries": sorted(set(countries)),
                    "reason": reason,
                })
                return
            # The registry is the authority that this platform exists; a
            # failed probe only withdraws the reachability claim.
            status = "unreachable"
        key = site_key_for_host(host)
        if key in sites:
            entry = sites[key]
            entry["countries"] = sorted(set(entry["countries"]) | set(countries))
            entry["source_keys"] = sorted(set(entry["source_keys"]) | set(source_keys))
            entry["wired"] = bool(entry["wired"] or wired)
            if registry_urls:
                entry["registry_urls"] = sorted(
                    set(entry.get("registry_urls", [])) | set(registry_urls)
                )
            return
        entry = {
            "name": name,
            "url": url,
            "host": host,
            "kind": kind,
            "status": status,
            "wired": bool(wired),
            "source_keys": sorted(set(source_keys)),
            "countries": sorted(set(countries)),
            "evidence": {
                "http_status": int(record.get("http_status") or 0),
                "checked_at_utc": str(record.get("checked_at_utc") or ""),
                "title": str(record.get("title") or ""),
                "challenge": bool(record.get("challenge")),
            },
        }
        if status == "unreachable":
            entry["evidence"]["probe_reason"] = reason
        if registry_urls:
            entry["registry_urls"] = sorted(set(registry_urls))
        sites[key] = entry

    # 1. Auction registry platforms grouped by shared host.
    registry, unmapped_registry_keys = registry_sources(manifest)
    live_rows = {
        row.get("source"): int(row.get("row_count") or 0)
        for row in (manifest.get("source_reports") or [])
    }
    by_host: Dict[str, Dict[str, Any]] = {}
    for source_key, entry in sorted(registry.items()):
        try:
            host = normalize_host(entry["url"])
        except ValueError:
            continue
        bucket = by_host.setdefault(host, {
            "countries": set(),
            "source_keys": set(),
            "urls": set(),
            "live": False,
            "names": [],
            "markets": set(),
        })
        market = AUCTION_REGISTRY_COUNTRIES[source_key]
        bucket["countries"].add(market)
        bucket["markets"].add(market)
        bucket["source_keys"].add(source_key)
        bucket["urls"].add(entry["url"])
        bucket["live"] = bucket["live"] or live_rows.get(source_key, 0) > 0
        bucket["names"].append((source_key, entry["name"]))
    for host, bucket in sorted(by_host.items()):
        eu_names = [name for key, name in bucket["names"] if AUCTION_REGISTRY_COUNTRIES[key] == "EU"]
        if eu_names:
            display_name = sorted(eu_names)[0]
        else:
            display_name = sorted(bucket["names"], key=lambda item: (len(item[1]), item[1]))[0][1]
        add_site(
            host=host,
            name=display_name,
            url=f"https://{host}/",
            kind="auction",
            countries=sorted(bucket["countries"]),
            source_keys=sorted(bucket["source_keys"]),
            wired=bool(bucket["live"]),
            registry_urls=sorted(bucket["urls"]),
        )

    # 2. Hand-curated classifieds, portals and dealer markets.
    for country, entries in sorted(CANDIDATES.items()):
        for _key, name, url, kind in entries:
            try:
                host = normalize_host(url)
            except ValueError:
                excluded.append({
                    "host": "",
                    "url": url,
                    "countries": [country],
                    "reason": "invalid_url",
                })
                continue
            add_site(
                host=host,
                name=name,
                url=url,
                kind=kind,
                countries=[country],
                source_keys=[],
                wired=False,
            )

    # 3. Countries: every declared market, including empty coverage.
    countries: List[Dict[str, Any]] = []
    for code in sorted(COUNTRIES):
        name_ar, name_en, flag = COUNTRIES[code]
        keys = sorted(key for key, entry in sites.items() if code in entry["countries"])
        countries.append({
            "code": code,
            "name": name_en,
            "name_ar": name_ar,
            "flag": flag,
            "site_keys": keys,
        })

    by_kind = {kind: 0 for kind in KINDS}
    by_status = {status: 0 for status in STATUSES}
    for entry in sites.values():
        by_kind[entry["kind"]] = by_kind.get(entry["kind"], 0) + 1
        by_status[entry["status"]] = by_status.get(entry["status"], 0) + 1
    excluded.sort(key=lambda item: (item["host"], item["url"]))

    return {
        "schema_version": SCHEMA_VERSION,
        "lane": LANE,
        "generated_at_utc": generated_at or utc_now_iso(),
        "contract": {
            "country_count": len(countries),
            "site_count": len(sites),
            "unique_host_count": len({entry["host"] for entry in sites.values()}),
            "https_only": True,
            "every_site_probed": True,
            "probe_checked_at_utc": str(probe.get("checked_at_utc", "")),
            "unmapped_registry_keys": unmapped_registry_keys,
        },
        "summary": {
            "countries": len(countries),
            "countries_with_sites": sum(1 for row in countries if row["site_keys"]),
            "sites": len(sites),
            "by_kind": by_kind,
            "by_status": by_status,
            "wired_sites": sum(1 for entry in sites.values() if entry["wired"]),
            "excluded": len(excluded),
        },
        "countries": countries,
        "sites": {key: sites[key] for key in sorted(sites)},
        "excluded": excluded,
    }


def validate_artifact(artifact: Any) -> Dict[str, Any]:
    """Fail-closed structural validation mirroring the browser contract."""
    if not isinstance(artifact, dict):
        raise ValueError("artifact must be an object")
    if artifact.get("schema_version") != SCHEMA_VERSION or artifact.get("lane") != LANE:
        raise ValueError("schema/lane mismatch")
    contract = artifact.get("contract")
    summary = artifact.get("summary")
    countries = artifact.get("countries")
    sites = artifact.get("sites")
    excluded = artifact.get("excluded")
    if not isinstance(contract, dict) or not isinstance(summary, dict):
        raise ValueError("contract/summary must be objects")
    if not isinstance(countries, list):
        raise ValueError("countries must be a list")
    if not isinstance(sites, dict):
        raise ValueError("sites must be an object")
    if not isinstance(excluded, list):
        raise ValueError("excluded must be a list")

    codes = [row.get("code") for row in countries]
    if codes != sorted(codes) or len(codes) != len(set(codes)):
        raise ValueError("country codes must be unique and sorted")
    if set(codes) != set(COUNTRIES):
        raise ValueError("country set must equal the declared European market set")
    if contract.get("country_count") != len(codes):
        raise ValueError("contract.country_count mismatch")
    unmapped = contract.get("unmapped_registry_keys")
    if not isinstance(unmapped, list) or unmapped != sorted(set(unmapped)) or not all(
        isinstance(key, str) and key for key in unmapped
    ):
        raise ValueError("contract.unmapped_registry_keys must be a sorted string array")

    seen_hosts: Dict[str, str] = {}
    references: Dict[str, set] = {code: set() for code in codes}
    for key, entry in sorted(sites.items()):
        if not isinstance(entry, dict):
            raise ValueError(f"site {key} must be an object")
        for field in ("name", "url", "host", "kind", "status"):
            if not isinstance(entry.get(field), str) or not entry.get(field):
                raise ValueError(f"site {key}: missing {field}")
        host = normalize_host(entry["url"])
        if host != entry["host"]:
            raise ValueError(f"site {key}: host does not match url")
        if host in seen_hosts:
            raise ValueError(f"duplicate host {host}")
        seen_hosts[host] = key
        if entry["kind"] not in KINDS:
            raise ValueError(f"site {key}: unknown kind")
        if entry["status"] not in STATUSES:
            raise ValueError(f"site {key}: unknown status")
        if not isinstance(entry.get("wired"), bool):
            raise ValueError(f"site {key}: wired must be boolean")
        if not isinstance(entry.get("source_keys"), list) or not isinstance(
            entry.get("countries"), list
        ):
            raise ValueError(f"site {key}: source_keys/countries must be arrays")
        site_countries = entry["countries"]
        if site_countries != sorted(set(site_countries)):
            raise ValueError(f"site {key}: countries must be unique and sorted")
        for code in site_countries:
            if code not in references:
                raise ValueError(f"site {key}: unknown country {code}")
            references[code].add(key)
        evidence = entry.get("evidence")
        if not isinstance(evidence, dict):
            raise ValueError(f"site {key}: evidence missing")
        if not isinstance(evidence.get("checked_at_utc"), str) or not evidence.get(
            "checked_at_utc"
        ):
            raise ValueError(f"site {key}: evidence timestamp missing")
        if not isinstance(evidence.get("http_status"), int) or evidence["http_status"] < 0:
            raise ValueError(f"site {key}: published without probe evidence")
        if not isinstance(evidence.get("challenge"), bool):
            raise ValueError(f"site {key}: evidence must record the challenge flag")
        if entry["status"] == "verified":
            if evidence["http_status"] not in REACHABLE_STATUSES or evidence["challenge"]:
                raise ValueError(f"site {key}: verified status without reachable evidence")
        elif entry["status"] == "walled":
            if evidence["http_status"] not in GATED_STATUSES and not evidence["challenge"]:
                raise ValueError(f"site {key}: walled status without gated evidence")
        elif evidence.get("probe_reason") not in EXCLUDE_REASONS:
            raise ValueError(f"site {key}: unreachable status must record its probe reason")
        if entry["wired"] and not entry["source_keys"]:
            raise ValueError(f"site {key}: wired site must carry source keys")
        if entry["kind"] == "auction" and not entry["source_keys"] and not entry.get(
            "registry_urls"
        ):
            raise ValueError(f"site {key}: auction site must carry registry evidence")

    total = len(sites)
    if contract.get("site_count") != total or summary.get("sites") != total:
        raise ValueError("site count mismatch")
    if contract.get("unique_host_count") != len(seen_hosts):
        raise ValueError("unique host count mismatch")

    for row in countries:
        if not isinstance(row, dict):
            raise ValueError("country row must be an object")
        keys = row.get("site_keys")
        if not isinstance(keys, list) or keys != sorted(keys) or len(keys) != len(set(keys)):
            raise ValueError(f"country {row.get('code')}: site_keys must be unique and sorted")
        if set(keys) != references[row["code"]]:
            raise ValueError(f"country {row.get('code')}: site_keys do not match site.countries")
        name_ar, name_en, flag = COUNTRIES[row["code"]]
        if (row.get("name_ar"), row.get("name"), row.get("flag")) != (name_ar, name_en, flag):
            raise ValueError(f"country {row.get('code')}: label mismatch")

    by_kind = summary.get("by_kind")
    by_status = summary.get("by_status")
    if not isinstance(by_kind, dict) or not isinstance(by_status, dict):
        raise ValueError("summary.by_kind/by_status must be objects")
    kind_counts: Dict[str, int] = {kind: 0 for kind in KINDS}
    status_counts: Dict[str, int] = {status: 0 for status in STATUSES}
    for entry in sites.values():
        kind_counts[entry["kind"]] += 1
        status_counts[entry["status"]] += 1
    if {k: by_kind.get(k, 0) for k in KINDS} != kind_counts:
        raise ValueError("by_kind mismatch")
    if {k: by_status.get(k, 0) for k in STATUSES} != status_counts:
        raise ValueError("by_status mismatch")
    if summary.get("wired_sites") != sum(1 for entry in sites.values() if entry["wired"]):
        raise ValueError("wired_sites mismatch")
    if summary.get("countries") != len(codes):
        raise ValueError("country summary mismatch")
    if summary.get("countries_with_sites") != sum(1 for row in countries if row["site_keys"]):
        raise ValueError("countries_with_sites mismatch")
    if summary.get("excluded") != len(excluded):
        raise ValueError("excluded summary mismatch")
    for item in excluded:
        if not isinstance(item, dict):
            raise ValueError("excluded entry must be an object")
        if item.get("reason") not in EXCLUDE_REASONS:
            raise ValueError(f"excluded entry carries unknown reason: {item.get('reason')}")
        if not isinstance(item.get("url"), str) or not item.get("url"):
            raise ValueError("excluded entry must carry its url")
        if not isinstance(item.get("countries"), list) or not item.get("countries"):
            raise ValueError("excluded entry must carry its countries")
    return {
        "countries": len(codes),
        "sites": total,
        "excluded": len(excluded),
        "wired": summary.get("wired_sites"),
    }


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    probe_cmd = sub.add_parser("probe", help="probe every candidate host once")
    probe_cmd.add_argument("--manifest", required=True, help="official_auction_watch.json path")
    probe_cmd.add_argument("--out", required=True, help="probe evidence output path")
    probe_cmd.add_argument("--workers", type=int, default=PROBE_WORKERS)

    build_cmd = sub.add_parser("build", help="build the published artifact")
    build_cmd.add_argument("--probe", required=True, help="probe evidence path")
    build_cmd.add_argument("--manifest", required=True, help="official_auction_watch.json path")
    build_cmd.add_argument("--out", required=True, help="artifact output path")
    build_cmd.add_argument("--generated-at", default=None)

    validate_cmd = sub.add_parser("validate", help="validate a published artifact")
    validate_cmd.add_argument("--artifact", required=True)

    args = parser.parse_args(argv)
    if args.command == "probe":
        manifest = json.loads(Path(args.manifest).read_text(encoding="utf-8"))
        registry, unmapped = registry_sources(manifest)
        targets = collect_probe_targets(registry)
        result = run_probe(targets, workers=args.workers)
        Path(args.out).write_text(
            json.dumps(result, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
        )
        reachable = sum(
            1 for row in result["results"] if classify_probe(row)[0] is not None
        )
        print(
            f"PROBED={len(targets)} REACHABLE={reachable} "
            f"EXCLUDED={len(targets) - reachable} UNMAPPED={len(unmapped)}"
        )
        return 0
    if args.command == "build":
        probe = json.loads(Path(args.probe).read_text(encoding="utf-8"))
        manifest = json.loads(Path(args.manifest).read_text(encoding="utf-8"))
        artifact = build_artifact(probe, manifest, generated_at=args.generated_at)
        stats = validate_artifact(artifact)
        Path(args.out).write_text(
            json.dumps(artifact, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
        )
        print(
            f"BUILT countries={stats['countries']} sites={stats['sites']} "
            f"wired={stats['wired']} excluded={stats['excluded']}"
        )
        return 0
    artifact = json.loads(Path(args.artifact).read_text(encoding="utf-8"))
    stats = validate_artifact(artifact)
    print(
        f"VALID countries={stats['countries']} sites={stats['sites']} "
        f"wired={stats['wired']} excluded={stats['excluded']}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
